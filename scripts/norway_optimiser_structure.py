"""Structure-check experiments for the Norway validation (task 3). Writes scenarios/experiments/stokstad_authors_variants.yaml
(a copy of scenarios/stokstad.yaml with three extra versions of the authors' pathway) and evaluates them on the 184 accepted
extended-grid settings (n=1000, seed 1) and at the shipped best fit (seeds 201-203, n=1000).

    python scripts/norway_optimiser_structure.py              # cached
    python scripts/norway_optimiser_structure.py --recompute

Variants of the authors' pathway ('optimal' in stokstad.yaml):
  optimal_nogate        treatment does not wait for tissue sampling to finish (paper: treatment is referred straight after the
                        tumour board, before the final diagnostic results; only the referral-to-treatment interval applies)
  optimal_petvisit      PET-CT is requested at the first consultation for everyone (the paper's formal definition) instead of the
                        fitted triage share of the observed practice
  optimal_petvisit_nogate   both
"""
from __future__ import annotations
import json, sys
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "scripts"))
import norway_optimiser_robust as R  # noqa: E402

EXP = ROOT / "scenarios" / "experiments" / "stokstad_authors_variants.yaml"
OUTJ = ROOT / "docs" / "review_checks" / "norway_opt_structure.json"
BEST_PT = {"bronch": 3, "surg": 6, "rt": 10.5, "cut": 0, "extra": 2, "pet": 1.0}  # = scenarios/generated/stokstad_calibrated.yaml
VARS = ["optimal_nogate", "optimal_petvisit", "optimal_petvisit_nogate"]


def make_experiment():
    lines = (ROOT / "scenarios" / "stokstad.yaml").read_text().splitlines()
    i0 = next(i for i, l in enumerate(lines) if l == "  optimal:")
    block = lines[i0:]
    out = list(lines)
    out.insert(0, "# EXPERIMENT (generated by scripts/norway_optimiser_structure.py): scenarios/stokstad.yaml plus three variants of the authors' pathway.")
    out.append("")
    for v in VARS:
        b = [l for l in block]
        b[0] = f"  {v}:"
        b[1] = f"    description: Authors' pathway, variant {v} (experiment)"
        for k, l in enumerate(b):
            if "pet_on_time: *pet_triage_mix" in l and "petvisit" in v:
                b[k] = "      pet_on_time: {mix: {pet_triage: 0.0, pet_early_route: 1.0}, source: experiment, note: PET-CT requested at the first consultation for everyone}"
            if "{id: treat, kind: exit" in l and "nogate" in v:
                assert "after: [mdt, sampling_done]" in l
                b[k] = l.replace("after: [mdt, sampling_done]", "after: [mdt]")
        out += b
    EXP.write_text("\n".join(out) + "\n")


def summ(rows, key, ref):
    d = [100 * (r[key]["share_within_target"] - r[ref]["share_within_target"]) for r in rows]
    s = [100 * r[key]["share_within_target"] for r in rows]
    return {"share": R.stats([x / 100 for x in s]), "minus_authors_pts": {k: round(float(v), 1) for k, v in zip(("min", "median", "max"), np.percentile(d, [0, 50, 100]))},
            "in_published_CI_72_87": sum(1 for x in s if 72 <= x <= 87)}


if __name__ == "__main__":
    rc = "--recompute" in sys.argv
    make_experiment()
    if "--best-only" in sys.argv:
        out = json.loads(OUTJ.read_text())
        best = R._work(("best", str(EXP), BEST_PT, ["observed", "optimal", "full_nofast", "full_fast", "no_d_nofast", "no_d_fast"] + VARS + ["only_bc_nofast", "only_bc_fast"], R.N, R.BEST_SEEDS))[1]
        out["best_fit_shipped_percent"] = {f: round(100 * v["share_within_target"], 1) for f, v in best.items()}
        OUTJ.write_text(json.dumps(out)); print(out["best_fit_shipped_percent"]); sys.exit()
    if OUTJ.exists() and not rc:
        print(json.dumps({k: v for k, v in json.loads(OUTJ.read_text()).items() if k != "rows"}, indent=1)); sys.exit()
    from norway_analyses import accepted
    tab = json.loads(R.TABLE.read_text()); acc = accepted(tab["rows"])
    fcs = ["optimal"] + VARS + ["only_bc_nofast", "only_bc_fast"]
    # nogate is also applied to the optimiser flowcharts? no: they keep the optimiser's own 'treatment waits for sampling' rule
    jobs = [(r["i"], str(EXP), r["pt"], fcs, R.N, [R.SEED]) for r in acc]
    with R.Pool(2) as p:
        res = dict(p.imap_unordered(R._work, jobs, chunksize=2))
    rows = [{"i": r["i"], "pt": r["pt"], "observed": r["observed"], "faster_pet": r["faster_pet"],
             **{f: res[r["i"]][f] for f in fcs}} for r in acc]
    best = R._work(("best", str(EXP), BEST_PT, ["observed", "optimal", "full_nofast", "full_fast", "no_d_nofast", "no_d_fast"] + VARS + ["only_bc_nofast", "only_bc_fast"], R.N, R.BEST_SEEDS))[1]
    # best fit with the PET triage share at 0 for observed too (as the review check did) is not needed: variants carry their own share
    out = {"n": R.N, "seed": R.SEED, "settings": len(rows),
           "grid_bands": {f: summ(rows, f, "optimal") for f in fcs},
           "grid_bands_vs_observed_pts": {f: {k: round(float(v), 1) for k, v in zip(("min", "median", "max"), np.percentile([100 * (r[f]["share_within_target"] - r["observed"]["share_within_target"]) for r in rows], [0, 50, 100]))} for f in fcs},
           "best_fit_shipped_percent": {f: round(100 * v["share_within_target"], 1) for f, v in best.items()},
           "rows": rows}
    OUTJ.write_text(json.dumps(out))
    print(json.dumps({k: v for k, v in out.items() if k != "rows"}, indent=1))
